import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

import { glOptions } from '@typegpu/gl';
import tgpu, { d } from 'typegpu';

// Glyph's public TypeGPU subpath exports whole shaders; the per-stage helpers below live in its built shader modules.
// They are resolved here, at build time only, into static WGSL and GLSL: nothing ships that imports them.
const glyphShaders = new URL('./dist/shaders/typegpu/', import.meta.resolve('@pmndrs/glyph/package.json'));
const { bitmapAtlasUv, bitmapPaintCoverageOpacity, bitmapQuadPosition } = await import(
  new URL('./bitmap-shader.js', glyphShaders).href
);
const { decorationPaint } = await import(new URL('./decoration-shader.js', glyphShaders).href);
const { MsdfRenderInput, msdfAtlasCoordinate, msdfClampedCoordinates, msdfPosition, msdfRender } = await import(
  new URL('./msdf-shader.js', glyphShaders).href
);

const bitmapFunctions = [
  tgpu.fn([d.vec2f, d.vec2f, d.vec2f], d.vec2f)(bitmapAtlasUv).$name('glyphBitmapAtlasUv'),
  tgpu.fn([d.f32, d.vec4f], d.vec2f)(bitmapPaintCoverageOpacity).$name('glyphBitmapPaintCoverageOpacity'),
  tgpu.fn([d.vec2f, d.vec2f, d.vec2f], d.vec3f)(bitmapQuadPosition).$name('glyphBitmapQuadPosition'),
];
const decorationPaintFn = tgpu.fn([d.vec2u], d.vec4f)(decorationPaint).$name('glyphDecorationPaint');
MsdfRenderInput.$name('GlyphMsdfRenderInput');
// GLSL ES 3.0 rejects a derivative anywhere in a vertex shader, even in a function the stage never calls, and PixiJS
// 3D's shared `gl.header` reaches both stages. Vertex helpers therefore resolve apart from the fragment-only ones,
// which go to `gl.fragment.header`. WGSL validates only what each entry point calls, so it keeps one header.
const msdfVertexFunctions = [
  decorationPaintFn,
  tgpu.fn([d.vec2f, d.vec2f, d.vec2f], d.vec2f)(msdfAtlasCoordinate).$name('glyphMsdfAtlasCoordinate'),
  tgpu.fn([d.vec2f, d.vec2f, d.vec3f], d.vec3f)(msdfPosition).$name('glyphMsdfPosition'),
];
const msdfFragmentFunctions = [
  tgpu.fn([d.vec2f, d.vec2f, d.vec4f, d.vec2f], d.vec4f)(msdfClampedCoordinates).$name('glyphMsdfClampedCoordinates'),
  tgpu.fn([MsdfRenderInput], d.vec4f)(msdfRender).$name('glyphMsdfRender'),
];
const msdfFunctions = [...msdfVertexFunctions, ...msdfFragmentFunctions];
const slugSource = await loadTransformedSource('slug-shader-source.js');
const slugWgsl = replaceHeaderWidth(tgpu.resolve(slugSource.slugFunctions), slugSource.slugHeaderWidthMarker);
const slugVertexGlsl = tgpu.resolve(slugSource.slugVertexFunctions, glOptions());
const slugFragmentGlsl = withoutDefinitions(
  replaceHeaderWidth(tgpu.resolve(slugSource.slugFragmentFunctions, glOptions()), slugSource.slugHeaderWidthMarker),
  slugVertexGlsl,
);
const msdfVertexGlsl = tgpu.resolve(msdfVertexFunctions, glOptions());
const msdfFragmentGlsl = withoutDefinitions(tgpu.resolve(msdfFragmentFunctions, glOptions()), msdfVertexGlsl);
const generated = `/** Generated by scripts/generate-shaders.mjs. Do not edit. */
export const decorationWgsl = ${JSON.stringify(tgpu.resolve([decorationPaintFn]))};
export const decorationGlsl = ${JSON.stringify(tgpu.resolve([decorationPaintFn], glOptions()))};
export const bitmapWgsl = ${JSON.stringify(tgpu.resolve(bitmapFunctions))};
export const bitmapGlsl = ${JSON.stringify(tgpu.resolve(bitmapFunctions, glOptions()))};
export const msdfWgsl = ${JSON.stringify(tgpu.resolve(msdfFunctions))};
/** GLSL for both stages; \`msdfFragmentGlsl\` holds what only the fragment stage may compile. */
export const msdfGlsl = ${JSON.stringify(msdfVertexGlsl)};
export const msdfFragmentGlsl = ${JSON.stringify(msdfFragmentGlsl)};
export const slugWgsl = ${JSON.stringify(slugWgsl)};
/** GLSL for both stages; \`slugFragmentGlsl\` holds what only the fragment stage may compile. */
export const slugGlsl = ${JSON.stringify(slugVertexGlsl)};
export const slugFragmentGlsl = ${JSON.stringify(slugFragmentGlsl)};
`;
const output = new URL('../src/generated/shaders.ts', import.meta.url);
await mkdir(dirname(fileURLToPath(output)), { recursive: true });
await writeFile(output, generated);

async function loadTransformedSource(name) {
  const sourceUrl = new URL(`./${name}`, import.meta.url);
  const transformedUrl = new URL(`./.${name}.${process.pid}.mjs`, import.meta.url);
  const sourcePath = fileURLToPath(sourceUrl);
  const { default: typegpuPlugin } = await import('unplugin-typegpu/rollup');
  const plugin = typegpuPlugin();
  const source = await readFile(sourceUrl, 'utf8');
  const transformed = await plugin.transform.handler.call({}, source, sourcePath);
  if (transformed === null || typeof transformed.code !== 'string') {
    throw new Error(`TypeGPU did not transform the Pixi3D shader build source ${name}`);
  }
  await writeFile(transformedUrl, transformed.code);
  try {
    return await import(`${transformedUrl.href}?build=${Date.now()}`);
  } finally {
    await rm(transformedUrl, { force: true });
  }
}

/** Drops the top-level definitions `shared` already makes, so one shader never defines a name twice. */
function withoutDefinitions(source, shared) {
  const defined = new Set(definitions(shared));
  const blocks = source.split('\n\n').filter((block) => !definitions(block).some((name) => defined.has(name)));
  const result = blocks.join('\n\n');
  const names = [...definitions(shared), ...definitions(result)];
  if (new Set(names).size !== names.length) throw new Error('Generated GLSL defines a name twice');
  return result;
}

function definitions(source) {
  return [...source.matchAll(/^(?:struct\s+(\w+)|[\w<>]+\s+(\w+)\s*\()/gmu)].map((match) => match[1] ?? match[2]);
}

function replaceHeaderWidth(source, marker) {
  const literal = `${marker}u`;
  if (!source.includes(literal)) throw new Error('Generated Slug shader omitted GLYPH_SLUG_HEADER_WIDTH');
  return source.replaceAll(literal, 'GLYPH_SLUG_HEADER_WIDTH');
}
