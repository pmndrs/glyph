// Re-encodes the vendored unicode-segmentation crate's grapheme, word, sentence and emoji category range
// tables as one three-stage trie over code points, keyed by the combined category tuple.
//
// The crate's own generated `tables.rs` (from its scripts/unicode.py) stores each property as sorted
// `(char, char, category)` rows: 12 bytes a row of code points that gzip cannot compress, about 23 kB gzip
// for the four tables. The same mapping as a trie of byte leaves is about 4 kB gzip. Lookups go from a
// binary search to three loads. The rows stay in `tables.rs` as the source of truth and the oracle: a
// test in the crate compares both encodings for every code point.
import { mkdir, readFile, writeFile } from 'node:fs/promises';

import { rustRows } from './support/code-point-trie.mjs';

const crate = new URL('../../../vendor/unicode-segmentation/', import.meta.url);
const input = new URL('src/tables.rs', crate);
const output = new URL('src/category_trie.rs', crate);
const check = process.argv.includes('--check');
const source = await readFile(input, 'utf8');

const LEAF_SHIFT = 7;
const MIDDLE_SHIFT = 5;
const CODE_POINTS = 0x110000;

const properties = [
  { table: 'grapheme_cat_table', module: 'grapheme', type: 'GraphemeCat', none: 'GC_Any' },
  { table: 'word_cat_table', module: 'word', type: 'WordCat', none: 'WC_Any' },
  { table: 'sentence_cat_table', module: 'sentence', type: 'SentenceCat', none: 'SC_Any' },
  { table: 'emoji_cat_table', module: 'emoji', type: 'EmojiCat', none: 'EC_Any' },
];

const character = (literal) => {
  const escaped = /^'\\u\{([0-9a-fA-F]+)\}'$/u.exec(literal);
  if (escaped !== null) return Number.parseInt(escaped[1], 16);
  const plain = /^'(.)'$/u.exec(literal);
  if (plain === null) throw new Error(`unexpected char literal ${literal}`);
  return plain[1].codePointAt(0);
};

/** Category per code point, by variant name; code points in no row keep the property's `_Any`. */
const columns = properties.map(({ table, type, none }) => {
  const body = new RegExp(`const ${table}: &\\[\\(char, char, ${type}\\)\\] = &\\[(.*?)\\];`, 'su').exec(source);
  if (body === null) throw new Error(`missing ${table}`);
  const rows = [...body[1].matchAll(/\(('(?:\\u\{[0-9a-fA-F]+\}|.)'),\s*('(?:\\u\{[0-9a-fA-F]+\}|.)'),\s*(\w+)\)/gu)];
  const declared = (body[1].match(/\(/gu) ?? []).length;
  if (rows.length !== declared) throw new Error(`${table}: parsed ${rows.length} of ${declared} rows`);
  const values = new Array(CODE_POINTS).fill(none);
  let previous = -1;
  for (const [, low, high, category] of rows) {
    const [start, end] = [character(low), character(high)];
    if (start <= previous || end < start) throw new Error(`${table} is not sorted and disjoint`);
    for (let codePoint = start; codePoint <= end; codePoint += 1) values[codePoint] = category;
    previous = end;
  }
  return values;
});

const tuples = new Map();
const tupleList = [];
const combined = new Uint8Array(CODE_POINTS);
for (let codePoint = 0; codePoint < CODE_POINTS; codePoint += 1) {
  const key = columns.map((column) => column[codePoint]).join(',');
  let index = tuples.get(key);
  if (index === undefined) {
    index = tupleList.length;
    if (index > 0xff) throw new Error('more than 256 category tuples');
    tuples.set(key, index);
    tupleList.push(columns.map((column) => column[codePoint]));
  }
  combined[codePoint] = index;
}

function dedupe(blocks) {
  const ids = new Map();
  const flat = [];
  const indices = blocks.map((block) => {
    const key = block.join(',');
    let id = ids.get(key);
    if (id === undefined) {
      id = ids.size;
      ids.set(key, id);
      flat.push(...block);
    }
    return id;
  });
  return { flat, indices };
}
const chunk = (values, size) => {
  const blocks = [];
  for (let index = 0; index < values.length; index += size) blocks.push(Array.from(values.slice(index, index + size)));
  return blocks;
};
const leaves = dedupe(chunk(combined, 1 << LEAF_SHIFT));
if (leaves.indices.length > 0 && Math.max(...leaves.indices) > 0xffff) throw new Error('too many leaves');
const middles = dedupe(chunk(leaves.indices, 1 << MIDDLE_SHIFT));
if (Math.max(...middles.indices) > 0xff) throw new Error('too many middle blocks');

const generated = `// Generated by packages/glyph/scripts/generate-segmentation-trie.mjs from src/tables.rs. Do not edit by hand.
//
// ${tupleList.length} category tuples, ${middles.indices.length} root entries, ${middles.flat.length / (1 << MIDDLE_SHIFT)} middle blocks, ${leaves.flat.length / (1 << LEAF_SHIFT)} leaves.

use crate::tables::{emoji::EmojiCat, grapheme::GraphemeCat, sentence::SentenceCat, word::WordCat};

pub(crate) const LEAF_SHIFT: u32 = ${LEAF_SHIFT};
pub(crate) const MIDDLE_SHIFT: u32 = ${MIDDLE_SHIFT};

/// \`(grapheme, word, sentence, emoji)\` categories; the leaves index this table.
pub(crate) static CATEGORIES: [(GraphemeCat, WordCat, SentenceCat, EmojiCat); ${tupleList.length}] = [
${tupleList.map((tuple) => `    (${tuple.map((name, index) => `${properties[index].type}::${name}`).join(', ')}),`).join('\n')}
];

/// Stage 1: \`ROOT[c >> (LEAF_SHIFT + MIDDLE_SHIFT)]\` is a middle block.
pub(crate) static ROOT: &[u8] = &[
${rustRows(middles.indices)}
];

/// Stage 2: \`MIDDLE[block << MIDDLE_SHIFT | (c >> LEAF_SHIFT) & mask]\` is a leaf.
pub(crate) static MIDDLE: &[u16] = &[
${rustRows(middles.flat)}
];

/// Stage 3: \`LEAVES[leaf << LEAF_SHIFT | c & mask]\` indexes \`CATEGORIES\`.
pub(crate) static LEAVES: &[u8] = &[
${rustRows(leaves.flat)}
];

/// The categories of \`c\`. Every index is in range by construction: the root covers every scalar
/// value, and the generator emits only middle and leaf indices it allocated.
#[inline]
pub(crate) fn categories(c: char) -> (GraphemeCat, WordCat, SentenceCat, EmojiCat) {
    let c = c as usize;
    let middle = usize::from(ROOT[c >> (LEAF_SHIFT + MIDDLE_SHIFT)]);
    let leaf = usize::from(MIDDLE[(middle << MIDDLE_SHIFT) | ((c >> LEAF_SHIFT) & ((1 << MIDDLE_SHIFT) - 1))]);
    CATEGORIES[usize::from(LEAVES[(leaf << LEAF_SHIFT) | (c & ((1 << LEAF_SHIFT) - 1))])]
}
`;

if (check) {
  let existing;
  try {
    existing = await readFile(output, 'utf8');
  } catch {
    existing = undefined;
  }
  if (existing !== generated) {
    console.error('generated segmentation trie is stale; run pnpm run unicode generate-data');
    process.exitCode = 1;
  }
} else {
  await mkdir(new URL('.', output), { recursive: true });
  await writeFile(output, generated);
  console.log(
    `segmentation trie: ${tupleList.length} tuples, ${middles.flat.length >> MIDDLE_SHIFT} middles, ${leaves.flat.length >> LEAF_SHIFT} leaves`,
  );
}
