import { createRequire } from 'node:module';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { gunzipSync } from 'node:zlib';

const require = createRequire(import.meta.url);
const output = new URL('../rust/shaper/src/generated/bidi_data.rs', import.meta.url);
const check = process.argv.includes('--check');

const classNames = new Map([
  ['Arabic_Letter', 'AL'],
  ['Arabic_Number', 'AN'],
  ['Boundary_Neutral', 'BN'],
  ['Common_Separator', 'CS'],
  ['European_Number', 'EN'],
  ['European_Separator', 'ES'],
  ['European_Terminator', 'ET'],
  ['First_Strong_Isolate', 'FSI'],
  ['Left_To_Right', 'L'],
  ['Left_To_Right_Embedding', 'LRE'],
  ['Left_To_Right_Isolate', 'LRI'],
  ['Left_To_Right_Override', 'LRO'],
  ['Nonspacing_Mark', 'NSM'],
  ['Other_Neutral', 'ON'],
  ['Paragraph_Separator', 'B'],
  ['Pop_Directional_Format', 'PDF'],
  ['Pop_Directional_Isolate', 'PDI'],
  ['Right_To_Left', 'R'],
  ['Right_To_Left_Embedding', 'RLE'],
  ['Right_To_Left_Isolate', 'RLI'],
  ['Right_To_Left_Override', 'RLO'],
  ['Segment_Separator', 'S'],
  ['White_Space', 'WS'],
]);

const bidiSource = gunzipSync(
  await readFile(new URL('../tests/fixtures/unicode-17.0.0/DerivedBidiClass.txt.gz', import.meta.url)),
).toString('utf8');
const scalarClasses = new Array(0x11_0000);
for (const line of bidiSource.split(/\r?\n/)) {
  const match = line.match(/^# @missing: ([0-9A-F]+)(?:\.\.([0-9A-F]+))?; (\w+)/);
  if (match === null) continue;
  fillRange(scalarClasses, match, classValue(match[3]));
}
for (const line of bidiSource.split(/\r?\n/)) {
  const match = line.match(/^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*(\w+)/);
  if (match === null) continue;
  fillRange(scalarClasses, match, classValue(match[3]));
}
if (scalarClasses.some((value) => value === undefined)) {
  throw new Error('DerivedBidiClass does not classify every Unicode code point');
}
// A two-stage code-point trie, the shape ICU calls UTrie2. Bidi classes are blocky, so a 128
// code-point block repeats heavily across the plane: deduplicating blocks turns a 1.1 MB flat
// array into a small stage-1 index plus a handful of distinct blocks. Lookup is then two array
// reads and no search, which matters because `bidi_class` is called per character on every
// analysis.
const BLOCK_SHIFT = 7;
const BLOCK_SIZE = 1 << BLOCK_SHIFT;
const classValues = [...new Set(scalarClasses)].sort();
const classIndex = new Map(classValues.map((value, index) => [value, index]));
const blockIndex = new Map();
const blocks = [];
const stage1 = [];
for (let base = 0; base < scalarClasses.length; base += BLOCK_SIZE) {
  const block = scalarClasses.slice(base, base + BLOCK_SIZE).map((value) => classIndex.get(value));
  const key = block.join(',');
  let index = blockIndex.get(key);
  if (index === undefined) {
    index = blocks.length;
    blockIndex.set(key, index);
    blocks.push(block);
  }
  stage1.push(index);
}
if (blocks.length > 0xff) {
  throw new Error(`stage-1 needs ${blocks.length} blocks, which no longer fits u8`);
}
if (classValues.length > 0xff) {
  throw new Error(`${classValues.length} bidi classes no longer fit u8`);
}
assertTrie();

const mirrors = require('@unicode/unicode-17.0.0/Bidi_Mirroring_Glyph/index.js');
const opens = codePoints('Open');
const closes = codePoints('Close');
const brackets = [];
for (const codePoint of [...opens, ...closes].sort((left, right) => left - right)) {
  const isOpen = opens.has(codePoint);
  const opening = isOpen ? codePoint : singleCodePoint(mirrors.get(codePoint), codePoint);
  const normalizedOpening = singleCodePoint(String.fromCodePoint(opening).normalize('NFD'), opening);
  brackets.push([codePoint, normalizedOpening, isOpen]);
}

const source = `// Generated by scripts/generate-unicode-bidi-data.mjs from
// @unicode/unicode-17.0.0@1.6.17. Do not edit by hand.
//
// Deliberately larger in raw bytes than the range table it replaces: this trades raw module size
// for lookup speed and gzip size. Raw costs a memcpy at instantiation; speed is paid per character.

use unicode_bidi::BidiClass;

pub const UNICODE_VERSION: &str = "17.0.0";

/// Distinct bidi classes, indexed by the values in \`BIDI_CLASS_STAGE2\`.
pub static BIDI_CLASS_VALUES: &[BidiClass] = &[
${classValues.map((value) => `    BidiClass::${value},`).join('\n')}
];

/// Stage 1 of the class trie: \`BIDI_CLASS_STAGE1[code_point >> ${BLOCK_SHIFT}]\` selects a block.
pub static BIDI_CLASS_STAGE1: &[u8] = &[
${rows(stage1)}
];

/// Stage 2: ${blocks.length} distinct ${BLOCK_SIZE}-code-point blocks of \`BIDI_CLASS_VALUES\` indices.
pub static BIDI_CLASS_STAGE2: &[u8] = &[
${rows(blocks.flat())}
];

/// \`code_point >> BIDI_CLASS_BLOCK_SHIFT\` indexes stage 1; the low bits index inside the block.
pub const BIDI_CLASS_BLOCK_SHIFT: usize = ${BLOCK_SHIFT};

pub const BIDI_BRACKETS: &[(u32, u32, bool)] = &[
${brackets.map(([codePoint, opening, isOpen]) => `    (0x${hex(codePoint)}, 0x${hex(opening)}, ${isOpen}),`).join('\n')}
];
`;

if (check) {
  let existing;
  try {
    existing = await readFile(output, 'utf8');
  } catch {
    existing = undefined;
  }
  if (existing !== source) {
    console.error('generated Unicode bidi data is stale; run pnpm run unicode generate-data');
    process.exitCode = 1;
  }
} else {
  await mkdir(new URL('../rust/shaper/src/generated/', import.meta.url), { recursive: true });
  await writeFile(output, source);
}

/// Sixteen values per line keeps the generated file reviewable without making it enormous.
function rows(values) {
  const lines = [];
  for (let index = 0; index < values.length; index += 16) {
    lines.push(`    ${values.slice(index, index + 16).join(', ')},`);
  }
  return lines.join('\n');
}

function codePoints(type) {
  const result = new Set();
  for (const { begin, end } of require(`@unicode/unicode-17.0.0/Bidi_Paired_Bracket_Type/${type}/ranges.js`)) {
    for (let codePoint = begin; codePoint < end; codePoint += 1) result.add(codePoint);
  }
  return result;
}

function classValue(value) {
  if ([...classNames.values()].includes(value)) return value;
  const mapped = classNames.get(value);
  if (mapped === undefined) throw new Error(`unmapped Bidi_Class value ${value}`);
  return mapped;
}

function fillRange(target, match, value) {
  const start = Number.parseInt(match[1], 16);
  const end = Number.parseInt(match[2] ?? match[1], 16) + 1;
  target.fill(value, start, end);
}

function singleCodePoint(value, codePointSource) {
  if (typeof value !== 'string') {
    throw new Error(`missing bidi mirror for U+${hex(codePointSource)}`);
  }
  const values = [...value];
  if (values.length !== 1) throw new Error(`expected one scalar for U+${hex(codePointSource)}`);
  const codePoint = values[0].codePointAt(0);
  if (codePoint === undefined) throw new Error(`missing scalar for U+${hex(codePointSource)}`);
  return codePoint;
}

/// Round-trips every scalar value through the emitted trie. A partition check would only prove
/// the ranges tile the plane; this proves the structure the engine will actually read returns the
/// class the Unicode data file assigned, for all 1,114,112 code points.
function assertTrie() {
  for (let codePoint = 0; codePoint < scalarClasses.length; codePoint += 1) {
    const block = blocks[stage1[codePoint >> BLOCK_SHIFT]];
    const decoded = classValues[block[codePoint & (BLOCK_SIZE - 1)]];
    if (decoded !== scalarClasses[codePoint]) {
      throw new Error(
        `trie decodes U+${hex(codePoint)} as ${decoded}, but DerivedBidiClass says ${scalarClasses[codePoint]}`,
      );
    }
  }
}

function hex(value) {
  return value.toString(16).toUpperCase();
}
