import { createRequire } from 'node:module';
import { mkdir, readFile, writeFile } from 'node:fs/promises';

import { EastAsianWidth } from '@cto.af/linebreak';
import { LineBreak, names } from '@cto.af/linebreak/lib/LineBreak.js';
import { resolve } from '@cto.af/linebreak/lib/state.js';

import { emitCodePointTrie } from './support/code-point-trie.mjs';

const require = createRequire(import.meta.url);
const output = new URL('../rust/shaper/src/generated/line_break_data.rs', import.meta.url);
const check = process.argv.includes('--check');
const initial = codePointSet('General_Category/Initial_Punctuation');
const final = codePointSet('General_Category/Final_Punctuation');
const extendedPictographic = codePointSet('Binary_Property/Extended_Pictographic');
const unassigned = codePointSet('General_Category/Unassigned');

const values = new Uint16Array(0x11_0000);
for (let codePoint = 0; codePoint < values.length; codePoint += 1) {
  const character = String.fromCodePoint(codePoint);
  const lineClass = resolve(LineBreak.get(codePoint), character);
  values[codePoint] =
    lineClass |
    (initial.has(codePoint) ? 1 << 8 : 0) |
    (final.has(codePoint) ? 1 << 9 : 0) |
    (EastAsianWidth.get(codePoint) ? 1 << 10 : 0) |
    (extendedPictographic.has(codePoint) && unassigned.has(codePoint) ? 1 << 11 : 0);
}

// Two-stage trie rather than sorted ranges: `properties` is called per character on every
// analysis, and this is deliberately larger raw and smaller over the wire. See D-341.
const trie = emitCodePointTrie({
  prefix: 'LINE_BREAK',
  valueAt: (codePoint) => values[codePoint],
  shift: 8,
  valueType: 'u32',
  describe: 'Line-break property bits.',
});

const constants = Object.entries(names)
  .sort((left, right) => left[1] - right[1])
  .map(([name, value]) => `pub const ${name}: u8 = ${value};`)
  .join('\n');
const source = `// Generated by scripts/generate-unicode-line-break-data.mjs from
// @cto.af/linebreak@4.0.3 and @unicode/unicode-17.0.0@1.6.17. Do not edit by hand.

pub const UNICODE_VERSION: &str = "17.0.0";
pub const INITIAL_PUNCTUATION: u32 = 1 << 8;
pub const FINAL_PUNCTUATION: u32 = 1 << 9;
pub const EAST_ASIAN: u32 = 1 << 10;
pub const UNASSIGNED_EXTENDED_PICTOGRAPHIC: u32 = 1 << 11;

${constants}

${trie}
`;

if (check) {
  let existing;
  try {
    existing = await readFile(output, 'utf8');
  } catch {
    existing = undefined;
  }
  if (existing !== source) {
    console.error('generated Unicode line-break data is stale; run pnpm run unicode generate-data');
    process.exitCode = 1;
  }
} else {
  await mkdir(new URL('../rust/shaper/src/generated/', import.meta.url), { recursive: true });
  await writeFile(output, source);
}

function codePointSet(path) {
  return new Set(require(`@unicode/unicode-17.0.0/${path}/code-points.js`));
}
