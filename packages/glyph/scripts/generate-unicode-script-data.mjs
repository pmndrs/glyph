import { createRequire } from 'node:module';
import { mkdir, readFile, writeFile } from 'node:fs/promises';

import { emitThreeStageTrie, planeFromRanges } from './support/code-point-trie.mjs';

const require = createRequire(import.meta.url);
const unicode = require('@unicode/unicode-17.0.0');
const propertyAliases = require('unicode-property-value-aliases');
const outputs = [
  {
    url: new URL('../rust/shaper/src/generated/script_data.rs', import.meta.url),
    source: () => rustSource(),
  },
];
const check = process.argv.includes('--check');

const scriptAliases = propertyAliases.get('Script');
const tagByScript = new Map();
for (const script of unicode.Script) {
  const aliases = [...scriptAliases]
    .filter(([alias, canonical]) => canonical === script && /^[A-Z][a-z]{3}$/.test(alias))
    .map(([alias]) => alias);
  if (aliases.length === 0) {
    throw new Error(`expected an ISO 15924 alias for ${script}`);
  }
  tagByScript.set(script, aliases[0]);
}

const primary = [];
const extensionEvents = new Map();
for (const script of unicode.Script) {
  const tag = tagToUint32(tagByScript.get(script));
  const ranges = require(`@unicode/unicode-17.0.0/Script/${script}/ranges.js`);
  for (const { begin, end } of ranges) primary.push([begin, end, tag]);

  const extensionRanges = require(`@unicode/unicode-17.0.0/Script_Extensions/${script}/ranges.js`);
  for (const { begin, end } of extensionRanges) {
    event(extensionEvents, begin).add.push(tag);
    event(extensionEvents, end).remove.push(tag);
  }
}

primary.sort(compareRange);
const primaryRanges = mergeRanges(primary);
assertCoverage(primaryRanges, 'Script');
const scriptPlane = planeFromRanges(primaryRanges, 'Script');

const extensionSets = [];
const extensionSetIndexes = new Map();
const extensionRanges = [];
const active = new Set();
const positions = [...extensionEvents].sort(([left], [right]) => left - right);
for (let index = 0; index < positions.length; index += 1) {
  const [position, changes] = positions[index];
  for (const tag of changes.remove) active.delete(tag);
  for (const tag of changes.add) active.add(tag);
  const next = positions[index + 1]?.[0] ?? 0x11_0000;
  if (next <= position) continue;
  const values = [...active].sort((left, right) => left - right);
  const key = values.join(',');
  let setIndex = extensionSetIndexes.get(key);
  if (setIndex === undefined) {
    setIndex = extensionSets.length;
    extensionSetIndexes.set(key, setIndex);
    extensionSets.push(values);
  }
  const previous = extensionRanges.at(-1);
  if (previous !== undefined && previous[1] === position && previous[2] === setIndex) {
    previous[1] = next;
  } else {
    extensionRanges.push([position, next, setIndex]);
  }
}
assertCoverage(extensionRanges, 'Script_Extensions');

// Script_Extensions as a sparse trie beside the script trie: 0 where the extensions are exactly the
// code point's own script, otherwise one plus the index of a set that differs. Most code points
// are 0, so the trie is small and the lookup needs no search.
const extensionPlane = new Uint8Array(0x11_0000);
const otherSets = [];
const otherSetIndexes = new Map();
for (const [begin, end, setIndex] of extensionRanges) {
  const values = extensionSets[setIndex];
  for (let codePoint = begin; codePoint < end; codePoint += 1) {
    if (values.length === 1 && values[0] === scriptPlane[codePoint]) continue;
    const key = values.join(',');
    let other = otherSetIndexes.get(key);
    if (other === undefined) {
      other = otherSets.length + 1;
      otherSetIndexes.set(key, other);
      otherSets.push(values);
    }
    extensionPlane[codePoint] = other;
  }
}
const extensionOffsets = [0];
const extensionTags = [];
for (const values of otherSets) {
  extensionTags.push(...values);
  extensionOffsets.push(extensionTags.length);
}

// Three-stage tries rather than sorted ranges: `script` and `script_extensions` are called per
// character in the scalar analysis. Three stages share the selector blocks of the mostly empty
// supplementary planes, which two stages repeat. See D-341.
const scriptTrie = emitThreeStageTrie({
  prefix: 'SCRIPT',
  valueAt: (codePoint) => scriptPlane[codePoint],
  leafShift: 6,
  middleShift: 5,
  valueType: 'u32',
  describe: 'ISO 15924 script tags packed as big-endian u32.',
});
const extensionTrie = emitThreeStageTrie({
  prefix: 'SCRIPT_EXTENSION',
  valueAt: (codePoint) => extensionPlane[codePoint],
  leafShift: 6,
  middleShift: 6,
  indexed: true,
});

function rustSource() {
  return `// Generated by scripts/generate-unicode-script-data.mjs from
// @unicode/unicode-17.0.0@1.6.17 and unicode-property-value-aliases@3.9.0.
// Do not edit by hand.

pub const UNICODE_VERSION: &str = "17.0.0";
pub const COMMON_SCRIPT: u32 = ${tagToUint32('Zyyy')};
pub const INHERITED_SCRIPT: u32 = ${tagToUint32('Zinh')};
pub const UNKNOWN_SCRIPT: u32 = ${tagToUint32('Zzzz')};

${scriptTrie}

/// Script_Extensions: a \`SCRIPT_EXTENSION\` leaf of 0 means the code point's own script alone;
/// \`n\` means \`SCRIPT_EXTENSION_TAGS[SCRIPT_EXTENSION_OFFSETS[n - 1]..SCRIPT_EXTENSION_OFFSETS[n]]\`.
${extensionTrie}
pub static SCRIPT_EXTENSION_OFFSETS: &[u16] = &${rustNumbers(extensionOffsets)};
pub static SCRIPT_EXTENSION_TAGS: &[u32] = &${rustNumbers(extensionTags)};
`;
}

if (check) {
  for (const output of outputs) {
    let existing;
    try {
      existing = await readFile(output.url, 'utf8');
    } catch {
      existing = undefined;
    }
    if (existing !== output.source()) {
      console.error('generated Unicode script data is stale; run pnpm run unicode generate-data');
      process.exitCode = 1;
    }
  }
} else {
  for (const output of outputs) {
    await mkdir(new URL('.', output.url), { recursive: true });
    await writeFile(output.url, output.source());
  }
}

function event(events, position) {
  let value = events.get(position);
  if (value === undefined) {
    value = { add: [], remove: [] };
    events.set(position, value);
  }
  return value;
}

function compareRange(left, right) {
  return left[0] - right[0] || left[1] - right[1] || left[2] - right[2];
}

function mergeRanges(ranges) {
  const merged = [];
  for (const range of ranges) {
    const previous = merged.at(-1);
    if (previous !== undefined && previous[1] === range[0] && previous[2] === range[2]) {
      previous[1] = range[1];
    } else {
      merged.push([...range]);
    }
  }
  return merged;
}

function assertCoverage(ranges, property) {
  let cursor = 0;
  for (const [start, end] of ranges) {
    if (start !== cursor || end <= start) {
      throw new Error(`${property} ranges are not a disjoint scalar-value partition at ${cursor}`);
    }
    cursor = end;
  }
  if (cursor !== 0x11_0000) {
    throw new Error(`${property} ranges stop at ${cursor}`);
  }
}

function tagToUint32(tag) {
  return tag.charCodeAt(0) * 0x1_000000 + tag.charCodeAt(1) * 0x1_0000 + tag.charCodeAt(2) * 0x100 + tag.charCodeAt(3);
}

function rustNumbers(values) {
  const rows = [];
  for (let index = 0; index < values.length; index += 24) {
    rows.push(`    ${values.slice(index, index + 24).join(', ')}`);
  }
  return `[\n${rows.join(',\n')}\n]`;
}
